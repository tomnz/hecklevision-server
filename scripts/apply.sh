#!/usr/bin/env bash
# Idempotent: run terraform apply, render the Ansible inventory from
# terraform outputs, then run the Ansible playbook.
#
# Arguments after `--` are passed through to ansible-playbook, e.g.:
#   ./scripts/apply.sh -- --tags update
#   ./scripts/apply.sh -- --check --diff
#   AUTO_APPROVE=1 ./scripts/apply.sh
#
# Set SKIP_TF=1 to skip terraform and just re-run ansible.
# Set SKIP_ANSIBLE=1 to only run terraform.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TF_DIR="$REPO_ROOT/infra/terraform"
ANS_DIR="$REPO_ROOT/ansible"
INVENTORY="$ANS_DIR/inventory.ini"

AUTO_APPROVE="${AUTO_APPROVE:-0}"
SKIP_TF="${SKIP_TF:-0}"
SKIP_ANSIBLE="${SKIP_ANSIBLE:-0}"

# Everything is passed through to ansible-playbook; a leading `--` is optional.
[[ "${1:-}" == "--" ]] && shift
ANSIBLE_EXTRA=("$@")

info()  { printf "\033[1;34m[info]\033[0m %s\n" "$*"; }
ok()    { printf "\033[1;32m[ ok ]\033[0m %s\n" "$*"; }
fail()  { printf "\033[1;31m[fail]\033[0m %s\n" "$*" >&2; exit 1; }

# --- Preflight ---------------------------------------------------------------

command -v terraform >/dev/null || fail "terraform not installed — run ./scripts/bootstrap.sh"
command -v ansible-playbook >/dev/null || fail "ansible-playbook not installed — run ./scripts/bootstrap.sh"
command -v jq >/dev/null || fail "jq not installed — run ./scripts/bootstrap.sh"

if ! aws sts get-caller-identity >/dev/null 2>&1; then
  fail "AWS CLI is not authenticated. Run 'aws configure', 'aws configure sso', or 'aws login' and retry."
fi

# Export AWS credentials into the environment so Terraform's provider picks
# them up. Works for the modern `aws login` flow (temporary STS credentials)
# as well as classic static keys. The Terraform provider's default credential
# chain doesn't understand the `aws login` session cache, so we bridge it here.
if aws configure export-credentials --format env >/tmp/aws-creds.$$ 2>/dev/null; then
  # shellcheck disable=SC1090
  source /tmp/aws-creds.$$
  rm -f /tmp/aws-creds.$$
  ok "AWS credentials exported to env for Terraform."
fi

[[ -f "$TF_DIR/terraform.tfvars" ]] || fail "Missing $TF_DIR/terraform.tfvars — copy from terraform.tfvars.example."

# --- Terraform ---------------------------------------------------------------

if [[ "$SKIP_TF" != "1" ]]; then
  info "terraform init"
  terraform -chdir="$TF_DIR" init -input=false

  info "terraform apply"
  if [[ "$AUTO_APPROVE" == "1" ]]; then
    terraform -chdir="$TF_DIR" apply -input=false -auto-approve
  else
    terraform -chdir="$TF_DIR" apply -input=false
  fi
  ok "Terraform apply complete."
else
  info "SKIP_TF=1 — skipping terraform."
fi

# --- Render inventory from outputs -------------------------------------------

info "Reading terraform outputs..."
TF_JSON="$(terraform -chdir="$TF_DIR" output -json)"

public_ip=$(jq -r '.public_ip.value' <<<"$TF_JSON")
ssh_key=$(jq -r '.ssh_private_key_path.value' <<<"$TF_JSON")
image_tag=$(jq -r '.image_tag.value' <<<"$TF_JSON")
data_volume_id=$(jq -r '.data_volume_id.value' <<<"$TF_JSON")
domain=$(jq -r '.domain.value' <<<"$TF_JSON")
app_upstream=$(jq -r '.app_upstream.value' <<<"$TF_JSON")

for v in public_ip ssh_key image_tag data_volume_id domain app_upstream; do
  [[ -n "${!v}" && "${!v}" != "null" ]] || fail "Missing terraform output: $v"
done

# Atomic write: tempfile + mv.
TMP_INV="$(mktemp "${INVENTORY}.XXXXXX")"
cat >"$TMP_INV" <<EOF
# Generated by scripts/apply.sh from terraform outputs. Do not edit.
[hecklevision]
server ansible_host=${public_ip} ansible_user=ubuntu ansible_ssh_private_key_file=${ssh_key}

[hecklevision:vars]
image_tag=${image_tag}
data_volume_id=${data_volume_id}
EOF
mv "$TMP_INV" "$INVENTORY"
ok "Wrote inventory: $INVENTORY"

# --- Ansible -----------------------------------------------------------------

if [[ "$SKIP_ANSIBLE" == "1" ]]; then
  info "SKIP_ANSIBLE=1 — skipping playbook."
  exit 0
fi

# --- Check instance is running before we SSH in ---------------------------------

instance_id=$(jq -r '.instance_id.value' <<<"$TF_JSON")
export AWS_REGION=$(jq -r '.region.value' <<<"$TF_JSON")
instance_state=$(aws ec2 describe-instance-status \
  --instance-ids "$instance_id" \
  --include-all-instances \
  --query 'InstanceStatuses[0].InstanceState.Name' \
  --output text 2>/dev/null || echo "unknown")

if [[ "$instance_state" != "running" ]]; then
  echo
  fail "EC2 instance $instance_id is '$instance_state', not 'running'. Start it first:
  ./scripts/start.sh"
fi

info "Running Ansible playbook"
cd "$ANS_DIR"

# Deployment settings from terraform.tfvars. Passed as JSON extra-vars so the
# lists stay real lists (key=value extra-vars are always strings).
EXTRA_VARS_JSON=$(jq -c '{
  domain: .domain.value,
  subdomains: .subdomains.value,
  extra_domains: .extra_domains.value,
  app_upstream: .app_upstream.value,
  timezone: .timezone.value
}' <<<"$TF_JSON")

ansible-playbook \
  -i "$INVENTORY" \
  site.yml \
  --extra-vars "$EXTRA_VARS_JSON" \
  ${ANSIBLE_EXTRA[@]+"${ANSIBLE_EXTRA[@]}"}

ok "Ansible playbook complete."
echo
echo "Next:"
echo "  SSH   → ./scripts/ssh.sh"
echo "  Status→ ./scripts/status.sh"
